-- ---------- updated_at triggers ----------
do $$
declare t text;
begin
  foreach t in array array['profiles','ocular_inspections','installation_records','master_data_catalog',
                           'photo_attachments','audit_logs','support_tickets','sales_leads','notifications']
  loop
    execute format('drop trigger if exists set_updated_at on public.%I', t);
    execute format('create trigger set_updated_at before update on public.%I for each row execute function public.set_updated_at()', t);
  end loop;
end $$;

-- ---------- role helper (security definer: bypasses RLS on profiles) ----------
create or replace function public.current_app_role()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select role from public.profiles
  where auth_user_id = auth.uid() and status = 'ACTIVE'
  limit 1;
$$;

revoke all on function public.current_app_role() from public;
grant execute on function public.current_app_role() to authenticated;

-- ---------- Row Level Security ----------
-- All tables except profiles: any signed-in user (role authenticated) has full access.
-- anon (not signed in) gets nothing: no policy grants it anything.
do $$
declare t text;
begin
  foreach t in array array['ocular_inspections','installation_records','master_data_catalog',
                           'photo_attachments','audit_logs','support_tickets','sales_leads','notifications']
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "authenticated full access" on public.%I', t);
    execute format('create policy "authenticated full access" on public.%I for all to authenticated using (true) with check (true)', t);
  end loop;
end $$;

-- profiles: everyone signed in can read; only admins can insert/update/delete.
alter table public.profiles enable row level security;
drop policy if exists "profiles select authenticated" on public.profiles;
drop policy if exists "profiles insert admin"         on public.profiles;
drop policy if exists "profiles update admin"         on public.profiles;
drop policy if exists "profiles delete admin"         on public.profiles;
create policy "profiles select authenticated" on public.profiles
  for select to authenticated using (true);
create policy "profiles insert admin" on public.profiles
  for insert to authenticated with check (public.current_app_role() = 'admin');
create policy "profiles update admin" on public.profiles
  for update to authenticated using (public.current_app_role() = 'admin')
  with check (public.current_app_role() = 'admin');
create policy "profiles delete admin" on public.profiles
  for delete to authenticated using (public.current_app_role() = 'admin');

-- ---------- Realtime ----------
-- Adds tables to the realtime publication, skipping any already added so re-runs do not error.
do $$
declare t text;
begin
  foreach t in array array['notifications','ocular_inspections','installation_records','sales_leads','support_tickets']
  loop
    if not exists (
      select 1 from pg_publication_tables
      where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = t
    ) then
      execute format('alter publication supabase_realtime add table public.%I', t);
    end if;
  end loop;
end $$;

