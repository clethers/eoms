-- =====================================================================
-- EOMS Supabase bridge schema
-- Paste this whole file into Supabase Dashboard -> SQL Editor -> Run.
-- It is idempotent: safe to re-run (tables are created only if missing,
-- policies/triggers are dropped and recreated, catalog seed skips existing keys).
--
-- Model: one table per app collection. The full app record lives in `data`
-- (jsonb); a few fields are "promoted" to real columns for filtering,
-- indexes and uniqueness. The app (js/services/localDb.js) writes both.
-- =====================================================================

-- ---------- updated_at trigger function ----------
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- ---------- tables ----------
create table if not exists public.profiles (
  id           bigint generated by default as identity primary key,
  data         jsonb not null default '{}',
  created_at   timestamptz default now(),
  updated_at   timestamptz default now(),
  auth_user_id uuid unique references auth.users(id) on delete set null,
  email        text unique,
  full_name    text,
  role         text constraint profiles_role_check check (role in ('admin','customer_care_manager','lead_engineer','operations')),
  status       text default 'ACTIVE' check (status in ('ACTIVE','SUSPENDED'))
);

create table if not exists public.ocular_inspections (
  id            bigint generated by default as identity primary key,
  data          jsonb not null default '{}',
