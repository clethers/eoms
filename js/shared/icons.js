/** SVG markup for a named icon (empty string for unknown names). */
export function icon(name) {
    const p = PATHS[name];
    if (!p) return '';
    return `<svg class="ic" viewBox="0 0 24 24" aria-hidden="true" focusable="false">${p}</svg>`;
}

/**
 * Button inner markup: icon + label span. The label is escaped.
 * Pass after=true to put the icon after the label (Next / forward actions).
 */
export function btnContent(name, label, after = false) {
    const text = `<span class="btn-label">${escapeHTML(label)}</span>`;
    return after ? `${text}${icon(name)}` : `${icon(name)}${text}`;
}

/** Change a button's visible label without losing its icon. */
export function setBtnLabel(btn, label) {
    if (!btn) return;
    const span = btn.querySelector('.btn-label');
    if (span) span.textContent = label;
    else btn.textContent = label;
}
